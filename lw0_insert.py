path = "docs/ELDER-LIVING-WORD.md"

with open(path, "r") as f:
    doc = f.read()

# --- Guards ---
marker = "## II. Design Laws"

if marker not in doc:
    sys.exit("MARKER NOT FOUND -- open the doc and confirm the Design Laws heading.")

if "LW-0" in doc:
    # Strip the stub and restore base doc before inserting full version
    cut = doc.find("## LW-0")
    if cut != -1:
        pre = doc[:cut].rstrip()
        post = doc[doc.find(marker, cut):]
        doc = pre + "\n\n" + post
        print("Stub found and stripped. Proceeding with full insertion.")
    else:
        sys.exit("LW-0 ALREADY PRESENT and could not be located for removal. Inspect the file manually.")

# --- Insert ---
doc = doc.replace(marker, insertion.strip() + "\n\n" + marker, 1)

with open(path, "w") as f:
    f.write(doc)

line_count = doc.count("\n")
print("LW-0 v0.2 inserted successfully.")
print("Total lines: " + str(line_count))

