#!/usr/bin/env node
// scripts/guardian-prompt-lock.mjs
//
// GUARDIAN PROMPT HASH CHECKER
//
// The adversarial probe suite contains synchronized copies of the guardian
// prompts from lib/dualGuardian.ts. If those prompts change without updating
// the probe suite, the suite silently tests last month's prompts while
// production runs different ones. This script makes that failure loud.
//
// It extracts JUDGE_A_SYSTEM and JUDGE_B_SYSTEM from dualGuardian.ts,
// computes SHA-256 hashes, and compares them to a lockfile. Any divergence
// fails immediately and loudly before a single probe runs.
//
// USAGE:
//   node scripts/guardian-prompt-lock.mjs           # verify (default)
//   node scripts/guardian-prompt-lock.mjs --update  # re-lock to current prompts
//   node scripts/guardian-prompt-lock.mjs --show    # print hashes only
//
// WORKFLOW:
//   1. You change JUDGE_A_SYSTEM in lib/dualGuardian.ts.
//   2. Run: node scripts/guardian-prompt-lock.mjs --update
//   3. Review the diff in .guardian-prompts.lock — confirm the change is intentional.
//   4. Update the synchronized copy in adversarial-probe.mjs to match.
//   5. Commit dualGuardian.ts + .guardian-prompts.lock + adversarial-probe.mjs together.
//
// Any probe run — including generative-probe.mjs — calls verifyPromptHashes()
// at startup and aborts if the lockfile is stale or missing.
//
// ADD TO package.json:
//   "lock:guardian":   "node scripts/guardian-prompt-lock.mjs",
//   "lock:guardian:up": "node scripts/guardian-prompt-lock.mjs --update"
//
// ADD TO GitHub Actions (before drift-detect and adversarial-probe):
//   - run: node scripts/guardian-prompt-lock.mjs
//     name: Verify guardian prompt hashes

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const GUARDIAN_TS   = resolve(__dirname, "../lib/dualGuardian.ts");
const LOCKFILE_PATH = resolve(__dirname, ".guardian-prompts.lock");

// ─────────────────────────────────────────────────────────────────────────────
// Extraction — reads dualGuardian.ts and pulls the two judge prompt strings.
//
// The extraction relies on the template literal format written in that file:
//   const JUDGE_A_SYSTEM = `...content...`;
//
// The prompts do not contain backtick characters, so finding the next
// backtick after the opening delimiter is a reliable closing boundary.
// If this extraction fails, that itself is a loud error — a format change
// to dualGuardian.ts requires updating this extractor too.
// ─────────────────────────────────────────────────────────────────────────────

function extractTemplateString(source, constName) {
  const marker = `const ${constName} = \``;
  const start  = source.indexOf(marker);
  if (start === -1) {
    throw new Error(
      `[guardian-prompt-lock] Cannot find '${constName}' in lib/dualGuardian.ts.\n` +
      `If the constant was renamed or reformatted, update the extractor.`
    );
  }
  const contentStart = start + marker.length;
  const closingTick  = source.indexOf("`", contentStart);
  if (closingTick === -1) {
    throw new Error(
      `[guardian-prompt-lock] Cannot find closing backtick for '${constName}'.`
    );
  }
  return source.slice(contentStart, closingTick);
}

function extractPrompts() {
  if (!existsSync(GUARDIAN_TS)) {
    throw new Error(
      `[guardian-prompt-lock] lib/dualGuardian.ts not found at expected path.\n` +
      `Run this script from the repository root.`
    );
  }
  const source = readFileSync(GUARDIAN_TS, "utf-8");
  return {
    judgeA: extractTemplateString(source, "JUDGE_A_SYSTEM"),
    judgeB: extractTemplateString(source, "JUDGE_B_SYSTEM"),
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// Hashing
// ─────────────────────────────────────────────────────────────────────────────

function sha256(content) {
  return "sha256:" + createHash("sha256").update(content, "utf-8").digest("hex");
}

function computeHashes(prompts) {
  return {
    judgeA: { hash: sha256(prompts.judgeA), length: prompts.judgeA.length },
    judgeB: { hash: sha256(prompts.judgeB), length: prompts.judgeB.length },
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// Lockfile
// ─────────────────────────────────────────────────────────────────────────────

function readLockfile() {
  if (!existsSync(LOCKFILE_PATH)) return null;
  try {
    return JSON.parse(readFileSync(LOCKFILE_PATH, "utf-8"));
  } catch {
    return null;
  }
}

function writeLockfile(hashes) {
  const lockData = {
    _note: "Auto-generated by scripts/guardian-prompt-lock.mjs. Commit alongside dualGuardian.ts changes.",
    lockedAt: new Date().toISOString(),
    judgeA: hashes.judgeA,
    judgeB: hashes.judgeB,
  };
  writeFileSync(LOCKFILE_PATH, JSON.stringify(lockData, null, 2) + "\n", "utf-8");
}

// ─────────────────────────────────────────────────────────────────────────────
// Verification — exported for use by probe scripts
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Verify that the guardian prompts in dualGuardian.ts match the lockfile.
 * Called at the start of every probe run. Throws with a clear message on mismatch.
 * Does NOT call process.exit() — lets the caller handle the error.
 */
export function verifyPromptHashes() {
  const prompts = extractPrompts();
  const current = computeHashes(prompts);
  const locked  = readLockfile();

  if (!locked) {
    throw new Error(
      `[guardian-prompt-lock] No lockfile found at scripts/.guardian-prompts.lock\n` +
      `Run: node scripts/guardian-prompt-lock.mjs --update\n` +
      `Commit the lockfile before running probes.`
    );
  }

  const aMatch = locked.judgeA?.hash === current.judgeA.hash;
  const bMatch = locked.judgeB?.hash === current.judgeB.hash;

  if (!aMatch || !bMatch) {
    const changed = [!aMatch && "JUDGE_A_SYSTEM", !bMatch && "JUDGE_B_SYSTEM"]
      .filter(Boolean)
      .join(", ");
    throw new Error(
      `[guardian-prompt-lock] Guardian prompts have changed since last lock: ${changed}\n\n` +
      `Locked:   A=${locked.judgeA?.hash ?? "missing"}  B=${locked.judgeB?.hash ?? "missing"}\n` +
      `Current:  A=${current.judgeA.hash}  B=${current.judgeB.hash}\n\n` +
      `Steps to resolve:\n` +
      `  1. Review the diff in lib/dualGuardian.ts — confirm the change is intentional.\n` +
      `  2. Update the synchronized copy in scripts/adversarial-probe.mjs to match.\n` +
      `  3. Run: node scripts/guardian-prompt-lock.mjs --update\n` +
      `  4. Commit dualGuardian.ts + .guardian-prompts.lock + adversarial-probe.mjs together.`
    );
  }
}

// ─────────────────────────────────────────────────────────────────────────────
// CLI
// ─────────────────────────────────────────────────────────────────────────────

const C = {
  reset: "\x1b[0m", bold: "\x1b[1m",
  green: "\x1b[32m", red: "\x1b[31m", yellow: "\x1b[33m", cyan: "\x1b[36m", gray: "\x1b[90m",
};

const args = process.argv.slice(2);

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const prompts = extractPrompts();
    const current = computeHashes(prompts);

    if (args.includes("--show")) {
      console.log(`\nJUDGE_A_SYSTEM  ${C.cyan}${current.judgeA.hash}${C.reset}  (${current.judgeA.length} chars)`);
      console.log(`JUDGE_B_SYSTEM  ${C.cyan}${current.judgeB.hash}${C.reset}  (${current.judgeB.length} chars)\n`);
      process.exit(0);
    }

    if (args.includes("--update")) {
      writeLockfile(current);
      console.log(`\n${C.green}✓${C.reset} Lockfile updated: scripts/.guardian-prompts.lock`);
      console.log(`  JUDGE_A  ${C.gray}${current.judgeA.hash}${C.reset}`);
      console.log(`  JUDGE_B  ${C.gray}${current.judgeB.hash}${C.reset}`);
      console.log(`\n${C.yellow}Next steps:${C.reset}`);
      console.log(`  1. Update the synchronized copy in scripts/adversarial-probe.mjs`);
      console.log(`  2. Commit dualGuardian.ts + .guardian-prompts.lock + adversarial-probe.mjs together\n`);
      process.exit(0);
    }

    // Default: verify
    verifyPromptHashes();
    const locked = readLockfile();
    console.log(`\n${C.green}✓${C.reset} Guardian prompt hashes verified (locked ${locked.lockedAt})\n`);

  } catch (err) {
    console.error(`\n${C.red}✗${C.reset} ${err.message}\n`);
    process.exit(1);
  }
}
